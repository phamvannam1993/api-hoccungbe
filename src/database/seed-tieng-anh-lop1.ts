// ── Bài tập (quizzes) — mỗi bài: ex1 = Dễ (10), ex2 = Trung bình (10), ex3 = Khó (10) ──
type Diff = 'easy' | 'medium' | 'hard';
type QSeed = { ex: number; type: string; text: string; opts: unknown; ans: unknown; diff: Diff; expl?: string };

const sc = (ex: number, diff: Diff, text: string, options: string[], correctIdx: number, expl?: string): QSeed => ({
  ex, diff, type: 'single_choice', text,
  opts: options.map((t, i) => ({ key: String.fromCharCode(65 + i), text: t })),
  ans: String.fromCharCode(65 + correctIdx), expl,
});
const tf = (ex: number, diff: Diff, text: string, answer: boolean, expl?: string): QSeed => ({ ex, diff, type: 'true_false', text, opts: null, ans: answer, expl });
const fb = (ex: number, diff: Diff, text: string, answer: string, expl?: string): QSeed => ({ ex, diff, type: 'fill_blank', text, opts: [{ key: 'b1', text: '' }], ans: { b1: answer }, expl });

